/* =============================================================================
   Canei Subirats — starter price book for building renovation (ES).

   Twenty chapters, ten partidas each. Loaded once by migration 16, which adds
   only what is absent and never touches an existing code, so a company that has
   already priced its own work keeps every figure it typed.

   WHAT THE NUMBERS ARE. Cost is what the work costs Canei; price is the
   reference selling price that lands in a quote. Both in integer CENTS, like
   everything else in this engine — never floats, because a price book that
   drifts by a cent per line is a quote that does not add up.

   They are realistic market figures for Barcelona-area reformas, not quotes:
   the operator is expected to edit them. A price book nobody edits is a price
   book nobody trusts, and starting from a plausible number is far quicker than
   starting from zero.

   `unit` values match the units list (m2, ml, ud, pa, h, kg, m3). `type` values
   match the catalogue's own list: material, ownLabour, subcontract, machinery,
   professional, waste, other.

   Rows are [code, desc, unit, type, costCents, priceCents, brand, model,
   quality] — an array rather than an object so two hundred lines stay readable
   as a table.

   WHAT BRAND / MODEL / QUALITY ARE FOR, and the rule for filling them. The same
   "punto de agua" at two qualities is two different prices and two different
   arguments on site six months later, and the only record of which was sold is
   the presupuesto. So:

     · `quality` is on EVERY row. It is the specification that distinguishes
       this partida from a cheaper or dearer version of the same job — "λ 0,035",
       "AC5", "nivel Q3", "manual", "maestreado", "tres manos".
     · `brand` and `model` are filled where the partida's price is dominated by
       a NAMED PRODUCT — materials, hired machinery, and the subcontracts that
       install a named system. They are blank on demolition, waste disposal,
       professional fees and general labour, because there is no manufacturer to
       name and inventing one would be worse than an honest blank. Neither is
       ever filled without the other.

   The names are plausible market choices for the Barcelona area, not the
   company's actual suppliers. Like the prices, they are a starting point the
   operator is expected to edit.
   ========================================================================== */
